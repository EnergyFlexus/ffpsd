def fourcc(code: str | bytes) -> int:
    """A four-character code as ffpsd keeps it, such as fourcc("lclr") for a layer's color label."""
    data = code.encode("latin-1") if isinstance(code, str) else bytes(code)
    if len(data) != 4:
        raise ValueError(f"a four-character code has 4 characters, not {len(data)}")
    return int.from_bytes(data, "big")


